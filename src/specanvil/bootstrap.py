def _module_md(ix: CodeIndex, module: str) -> str:
    files = ix.module_files(module)
    q = ",".join("?" * len(files))
    syms = ix.db.execute(
        f"SELECT path, qualname, kind, signature, doc, exported FROM symbols WHERE path IN ({q}) AND parent='' "
        "ORDER BY exported DESC, tokens DESC LIMIT 25", files).fetchall() if files else []
    imports = ix.db.execute(f"SELECT source FROM imports WHERE path IN ({q})", files).fetchall() if files else []
    deps: Counter = Counter()
    for (src,) in imports:
        m = re.search(r"(?:from|import|require\(|using)\s+['\"]?([@\w./\-]+)", src)
        if m:
            deps[m.group(1).split("/")[0] if not m.group(1).startswith(".") else "(relative)"] += 1
    tests = [f for f in files if re.search(r"(test|spec)", f, re.I)]
    lines = [f"# Module: {module}", "status: generated (needs review)", "",
             "## Purpose", "_TODO (run /sa:learn): what this module is responsible for and why it exists._", "",
             "## Public API"]
    for s in syms:
        doc = f" — {s['doc']}" if s["doc"] else ""
        lines.append(f"- `{s['path']}::{s['qualname']}` ({s['kind']}){doc}")
    lines += ["", "## Files", *[f"- `{f}`" for f in files[:30]]]
    if len(files) > 30:
        lines.append(f"- … and {len(files) - 30} more")
    lines += ["", "## Dependencies", "- " + (", ".join(f"`{d}`" for d, _ in deps.most_common(12)) or "none found"), "",
              "## Tests", *([f"- `{t}`" for t in tests[:10]] or ["- none found in this module"]), "",
              "## Key flows", "_TODO_", "", "## Business rules", "_TODO_", "",
              "## Needs human review",
              "- This spec was reverse-engineered from code: it describes what the code does, which may include bugs.", ""]
    return "\n".join(lines)


