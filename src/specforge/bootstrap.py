def _conventions_skill(name: str, conv: dict, stack: dict, values: dict) -> str:
    ex = "\n".join(f"- {label}: " + "; ".join(f"`{e}`" for e in exs) for label, exs in conv["archetypes"].items())
    return f"""---
name: {name}-conventions
description: How code is written in {name} - naming, layout, testing, commands and reference implementations to copy. Use before writing or reviewing any code in this repo.
---

# {name} conventions

- Functions: {conv['function_naming']} · Types: {conv['type_naming']} · Files: {conv['file_naming']}
- Tests: {conv['test_style']} in {', '.join(conv['test_locations']) or 'n/a'} ({', '.join(stack['test_frameworks']) or 'framework not detected'})
- Lint/format config: {', '.join(conv['lint_and_format']) or 'none found'}
- Test: `{values['test_cmd']}` · Lint: `{values['lint_cmd']}` · Dev: `{values['dev_cmd']}`
{("- Sub-projects (run commands from inside each folder):" + chr(10) + _subproject_lines(stack)) if _subproject_lines(stack) else ""}

## Reference implementations (open with get_symbol / file_outline, then mirror them)
{ex or '- none detected yet'}

## Rules
1. Match the nearest existing example over general best practice when they conflict; note the conflict.
2. New code gets tests in the same style and location as its neighbours.
3. Full details: `{values['specs_dir']}/conventions.md` (read by section).
"""


def _stack_skill(kind: str, name: str, stack: dict, conv: dict, values: dict) -> str:
    if kind == "frontend":
        libs = stack["frontend"] + stack["mobile"]
        labels = ["Components", "Hooks", "Pages / views"]
        recipe = ["Find the closest existing component (`search_symbols`) and open it with `get_symbol`.",
                  "Create the new file next to similar ones, same naming and export style.",
                  "Fetch data the way neighbours do; handle loading / empty / error states.",
                  "Add `data-testid`s from the design; keep accessible roles and labels.",
                  "Add a component test in the same style; run `" + values["test_cmd"] + "`."]
    else:
        libs = stack["backend"] + stack["orm"] + [f"{d} database" for d in stack["databases"]]
        labels = ["Controllers / routes", "Routes", "Handlers", "Services", "Repositories / DAOs",
                  "Models / entities", "Entities", "DTOs / schemas", "Schemas", "Migrations", "Middleware"]
        recipe = ["Find the closest existing endpoint (`search_symbols`) and follow its layering exactly.",
                  "Define request/response types and validation first.",
                  "Put logic in the service layer; keep handlers thin.",
                  "Persistence: no N+1, select needed columns, paginate lists; write a migration if schema changes.",
                  "Unit-test the service, integration-test the endpoint; run `" + values["test_cmd"] + "`."]
    ex = "\n".join(f"- {l}: " + "; ".join(f"`{e}`" for e in conv["archetypes"][l])
                   for l in labels if l in conv["archetypes"])
    steps = "\n".join(f"{i}. {s}" for i, s in enumerate(recipe, 1))
    return f"""---
name: {kind}-patterns
description: How {kind} code is built in {name} ({', '.join(libs) or 'stack not detected'}). Use for /sf:{'fe' if kind == 'frontend' else 'be'} and any {kind} change.
---

# {kind.title()} patterns for {name}

Stack: {', '.join(libs) or 'not detected'}

## Examples in this repo
{ex or '- none detected yet — run /sf:learn'}

## Recipe
{steps}
{(chr(10) + "## Sub-project commands" + chr(10) + _subproject_lines(stack)) if _subproject_lines(stack) else ""}

_Generated by specforge init. Run /sf:learn to replace this with a precise, repo-specific recipe._
"""


def _db_skill(engines: list[str]) -> str:
    known = ["postgres", "mysql", "sqlserver", "mongodb", "sqlite"]
    chosen = [e for e in engines if e in known] or known
    body = asset("skills/db-optimization/engines/generic.md")
    for e in chosen:
        body += "\n" + asset(f"skills/db-optimization/engines/{e}.md")
    return f"""---
name: db-optimization
description: Database performance checklist for {', '.join(chosen)} - plans, indexes, N+1, pagination, safe migrations. Use for /sf:db and any query or schema change.
---

# Database optimisation ({', '.join(chosen)})

{body}"""


