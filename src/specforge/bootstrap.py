def _project_md(root: Path, stack: dict, ix: CodeIndex, connectors: list[str]) -> str:
    st = ix.stats()
    rows = lambda items: ", ".join(items) if items else "—"  # noqa: E731
    lines = [f"# {root.name}: project spec", "status: generated (curate me)", "",
             "> Generated by `specforge init` from static analysis. Run `/sf:learn` to enrich, then review.", "",
             "## Overview", "_What this product does, for whom, and the main user journeys. (fill in)_", "",
             "## Stack",
             "| Area | Detected |", "|---|---|",
             "| Languages | " + rows(["%s (%d files)" % (l["lang"], l["files"]) for l in stack["languages"]]) + " |",
             f"| Frontend | {rows(stack['frontend'] + stack['mobile'])} |",
             f"| Backend | {rows(stack['backend'])} |",
             f"| Data access | {rows(stack['orm'])} |",
             f"| Databases | {rows(stack['databases'])} |",
             f"| Tests | {rows(stack['test_frameworks'])} |",
             f"| CI | {rows(stack['ci'])} |",
             f"| Tickets | {rows(stack['ticket_systems'])}" + (f" (keys: {', '.join(stack['ticket_keys'])})" if stack['ticket_keys'] else "") + " |",
             "", f"Size: {st['files']} files, {st['lines']:,} lines, {st['symbols']:,} symbols (~{st['repo_tokens']:,} tokens to read in full).",
             "", "## Commands", "| Task | Command |", "|---|---|"]
    lines += [f"| {k} | `{v}` |" for k, v in stack["commands"].items()] or ["| — | not detected |"]
    if stack.get("projects"):
        lines += ["", "### Sub-projects", "| Path | Manifests | Test command |", "|---|---|---|"]
        lines += [f"| `{p['path']}` | {', '.join(p['manifests'])} | `{p['commands'].get('test', '—')}` |"
                  for p in stack["projects"]]
    lines += ["", "## Modules", "| Module | Files | Lines | Spec |", "|---|---|---|---|"]
    for m in ix.modules()[:40]:
        lines.append(f"| {m['m']} | {m['files']} | {m['lines']:,} | [modules/{_slug(m['m'])}.md](modules/{_slug(m['m'])}.md) |")
    lines += ["", "## Architecture", "_How modules talk to each other (fill in, or let /sf:learn draft a Mermaid diagram)._", "",
              "## MCP connectors", ", ".join(f"`{c}`" for c in connectors), ""]
    return "\n".join(lines)


def _conventions_md(conv: dict, stack: dict) -> str:
    lines = ["# Conventions", "status: generated (curate me)", "",
             "> Learned from the code by `specforge init`. These describe how the code *is* written. Edit to match how it *should* be.", "",
             "## Naming",
             f"- Functions/methods: **{conv['function_naming']}**",
             f"- Types/classes: **{conv['type_naming']}**",
             f"- Files: **{conv['file_naming']}**", "",
             "## Layout",
             "- Top-level folders: " + ", ".join(f"`{d}`" for d in conv["top_level_dirs"]), "",
             "## Testing",
             f"- {conv['test_files']} test files for {conv['source_files']} source files.",
             f"- Style: {conv['test_style']}; locations: " + ", ".join(f"`{d}`" for d in conv["test_locations"]),
             "- Frameworks: " + (", ".join(stack["test_frameworks"]) or "not detected"), "",
             "## Lint & format", "- " + (", ".join(f"`{x}`" for x in conv["lint_and_format"]) or "no config found"), "",
             "## Reference implementations",
             "Copy these when adding something of the same kind:"]
    for label, ex in conv["archetypes"].items():
        lines.append(f"- **{label}**: " + "; ".join(f"`{e}`" for e in ex))
    lines += ["", "## Rules", "_Add team rules here (error handling, logging, DTO mapping, i18n...). /sf:learn will draft some._", ""]
    return "\n".join(lines)


def _module_md(ix: CodeIndex, module: str) -> str:
    files = ix.module_files(module)
    q = ",".join("?" * len(files))
    syms = ix.db.execute(
        f"SELECT path, qualname, kind, signature, doc, exported FROM symbols WHERE path IN ({q}) AND parent='' "
        "ORDER BY exported DESC, tokens DESC LIMIT 25", files).fetchall() if files else []
    imports = ix.db.execute(f"SELECT source FROM imports WHERE path IN ({q})", files).fetchall() if files else []
    deps = Counter()
    for (src,) in imports:
        m = re.search(r"(?:from|import|require\(|using)\s+['\"]?([@\w./\-]+)", src)
        if m:
            deps[m.group(1).split("/")[0] if not m.group(1).startswith(".") else "(relative)"] += 1
    tests = [f for f in files if re.search(r"(test|spec)", f, re.I)]
    lines = [f"# Module: {module}", "status: generated (needs review)", "",
             "## Purpose", "_TODO (run /sf:learn): what this module is responsible for and why it exists._", "",
             "## Public API"]
    for s in syms:
        doc = f" — {s['doc']}" if s["doc"] else ""
        lines.append(f"- `{s['path']}::{s['qualname']}` ({s['kind']}){doc}")
    lines += ["", "## Files", *[f"- `{f}`" for f in files[:30]]]
    if len(files) > 30:
        lines.append(f"- … and {len(files) - 30} more")
    lines += ["", "## Dependencies", "- " + (", ".join(f"`{d}`" for d, _ in deps.most_common(12)) or "none found"), "",
              "## Tests", *([f"- `{t}`" for t in tests[:10]] or ["- none found in this module"]), "",
              "## Key flows", "_TODO_", "", "## Business rules", "_TODO_", "",
              "## Needs human review",
              "- This spec was reverse-engineered from code: it describes what the code does, which may include bugs.", ""]
    return "\n".join(lines)


