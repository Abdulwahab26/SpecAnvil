MARK_START = "<!-- specforge:start -->"
MARK_END = "<!-- specforge:end -->"
COMMANDS = ["groom", "design", "plan", "fe", "be", "db", "qa", "e2e", "verify", "flow", "ship", "status",
            "learn", "spec", "test-plan", "test-run", "backfill", "profile", "docs", "summarize", "analyze"]


def asset(path: str) -> str:
    return resources.files("specforge").joinpath(f"assets/{path}").read_text(encoding="utf-8")


def asset_dir(path: str):
    return resources.files("specforge").joinpath(f"assets/{path}")


@dataclass
class Plan:
    root: Path
    dry_run: bool = False
    force: bool = False
    actions: list[tuple[str, str]] = field(default_factory=list)

    def write(self, rel: str, content: str, overwrite: bool = False) -> None:
        p = self.root / rel
        if p.exists() and not (overwrite or self.force):
            self.actions.append(("keep", rel))
            return
        self.actions.append(("update" if p.exists() else "create", rel))
        if not self.dry_run:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content, encoding="utf-8")


def _fill(text: str, values: dict) -> str:
    return re.sub(r"\{\{(\w+)\}\}", lambda m: str(values.get(m.group(1), m.group(0))), text)


def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or "root"


def _subproject_lines(stack: dict) -> str:
    rows = []
    for p in stack.get("projects", []):
        c = p["commands"]
        parts = [f"{k}: `{c[k]}`" for k in ("test", "build", "dev", "lint") if k in c]
        if parts:
            rows.append(f"- `{p['path']}/` — " + " · ".join(parts))
    return "\n".join(rows)


def _values(root: Path, cfg: dict, stack: dict) -> dict:
    cmds = stack.get("commands", {})
    missing = "(not detected — set in .specforge/config.json)"
    return {
        "project_name": root.name, "specs_dir": cfg["specs_dir"],
        "test_cmd": cmds.get("test", "the project's test command " + missing),
        "lint_cmd": cmds.get("lint", "the project's linter " + missing),
        "build_cmd": cmds.get("build", missing), "dev_cmd": cmds.get("dev", "the dev server command " + missing),
        "e2e_cmd": cmds.get("e2e", "npx playwright test"), "app_url": cfg.get("app_url", "http://localhost:3000"),
        "tickets": cfg.get("tickets") or "none detected", "databases": ", ".join(cfg.get("databases") or []) or "none detected",
        "budget": cfg.get("context_budget_tokens", 6000),
    }


